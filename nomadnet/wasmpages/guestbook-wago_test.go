// TestExampleGuestbookRejectsMarkupInjection pins the store-time mitigation:
// a submission carrying Micron's formatting character or a link opener is
// rejected outright, so the rendered page can never re-emit visitor markup.
func TestExampleGuestbookRejectsMarkupInjection(t *testing.T) {
	for _, tc := range []struct {
		name string
		data map[string]string
	}{
		{
			name: "backtick in message",
			data: map[string]string{"field_name": "Evil", "field_message": "`[click`https://example.invalid]"},
		},
		{
			name: "bracket in message",
			data: map[string]string{"field_name": "Evil", "field_message": "[click me]"},
		},
		{
			name: "backtick in name",
			data: map[string]string{"field_name": "Ev`il", "field_message": "hello"},
		},
		{
			name: "bracket in name",
			data: map[string]string{"field_name": "Ev[il", "field_message": "hello"},
		},
		{
			name: "newline injection",
			data: map[string]string{"field_name": "Evil\n>Fake Heading", "field_message": "hello"},
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			render, _ := guestbookExample(t)
			got := render(PageRequest{RequestData: tc.data})
			want := ">Guestbook\n\n" + guestbookForm + "No entries yet.\n"
			if got != want {
				t.Errorf("injecting submission rendered\n%q\nwant\n%q", got, want)
			}
			if strings.Contains(got, "example.invalid") || strings.Contains(got, "Fake Heading") {
				t.Errorf("rendered markup carries visitor markup: %q", got)
			}
		})
	}
}

