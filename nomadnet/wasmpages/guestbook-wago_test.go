// The instants the tests stamp submissions with: 2026-09-11 21:08:27 EST, the
// example in the timestamp construct's documentation, and six seconds later.
const (
	stampFirst  = 1789178907
	stampSecond = 1789178913
)

// visitPartial is the quiet site-counter partial the guestbook embeds at the end
// of its visit line: the partial names no page, so it counts the node's
// site-wide total, and "quiet=1" makes the counter module render nothing, so
// opening the guestbook bumps that total without printing it here.
const visitPartial = "`{:/page/hit-counter.wasm`0`quiet=1}"

// guestbookForm is the block every render opens with, right under the heading:
// the form first, so a visitor never has to scroll past the whole history to
// sign it, then its usage tip, then a divider before the entries. The fields
// are labelled page text with empty, background-highlighted boxes (a Micron
// field's VALUE slot is pre-defined content, not a hint — see
// assets/wasm-pages/guestbook.wat "FORM MARKUP").
const guestbookForm = "Name: `B444`<name`>`b\n" +
	"Message: `B444`<32|message`>`b\n" +
	"`[Sign the guestbook`:/page/guestbook.wasm`name|message]\n" +
	"\n`!Using the form`!: the selected field has the keyboard, so just type. " +
	"`!Down`! / `!Up`! (or `!Tab`!) move between fields, and `!Enter`! on the " +
	"`!Sign the guestbook`! line submits what you typed. Every field is a " +
	"readline-style editor: `!Ctrl-A`! / `!Ctrl-E`! start / end of the line, " +
	"`!Ctrl-U`! clears back to the start, `!Ctrl-K`! clears to the end, " +
	"`!Ctrl-W`! deletes a word, `!Ctrl-L`! clears the field, and `!Ctrl-Y`! " +
	"pastes back what you cleared.\n" +
	"\n----\n\n"

// visitLine is the line the page prints after its usage tip and before the
// divider: how many times the guestbook itself has been opened, then the quiet
// partial that counts the node as a whole.
func visitLine(visits uint32) string {
	word := "times"
	if visits == 1 {
		word = "time"
	}
	return fmt.Sprintf("Guestbook has been visited %v %v.%v\n", visits, word, visitPartial)
}

// withoutVisitLine drops the visit line, whose count grows with every render a
// test performs (the page counts each one), so a test can pin the rest of the
// page exactly.
func withoutVisitLine(page string) string {
	var kept []string
	for _, line := range strings.Split(page, "\n") {
		if strings.HasPrefix(line, "Guestbook has been visited ") {
			continue
		}
		kept = append(kept, line)
	}
	return strings.Join(kept, "\n")
}

// guestbookExample copies the shipped guestbook into a fresh pages directory and
// returns the render function for it plus that directory, so the KV store lands
// in the pages directory rather than next to the checked-in binary. The render
// function drops the visit line, whose count depends on how many times the test
// has already rendered; the tests that pin the visit line use
// guestbookRawExample.
func guestbookExample(t *testing.T) (func(req PageRequest) string, string) {
	t.Helper()
	render, pages := guestbookRawExample(t)
	return func(req PageRequest) string {
		t.Helper()
		return withoutVisitLine(render(req))
	}, pages
}

// guestbookRawExample is guestbookExample without the visit-line stripping, for
// the tests that pin the visit line and the site-counter partial themselves.
func guestbookRawExample(t *testing.T) (func(req PageRequest) string, string) {
	t.Helper()
	src, err := os.ReadFile(filepath.Join("..", "..", "assets", "wasm-pages", "guestbook.wasm"))
	if err != nil {
		t.Fatalf("ReadFile: %v", err)
	}
	pages := tempDir(t)
	path := filepath.Join(pages, "guestbook.wasm")
	if err := os.WriteFile(path, src, 0o644); err != nil {
		t.Fatalf("WriteFile: %v", err)
	}
	return func(req PageRequest) string {
		t.Helper()
		req.Path = "/page/guestbook.wasm"
		markup, err := Render(path, req)
		if err != nil {
			t.Fatalf("Render: %v", err)
		}
		return string(markup)
	}, pages
}

