// TestExampleGuestbookStoreLayout pins the on-disk keys and the stored entry
// shape: the count lives under "n" as a little-endian u32, and each entry under
// "e<index>" as "<unix-seconds>\t<name>: <message>\n", so the seconds survive
// in the store and the page can render them for whoever is reading.
func TestExampleGuestbookStoreLayout(t *testing.T) {
	render, pages := guestbookExample(t)

	render(PageRequest{RequestedAt: stampFirst, RequestData: map[string]string{
		"field_name":    "Glenn",
		"field_message": "first",
	}})

	storeDir := filepath.Join(pages, "data", "guestbook")
	count, err := os.ReadFile(filepath.Join(storeDir, "n"))
	if err != nil {
		t.Fatalf("ReadFile(n): %v", err)
	}
	if len(count) != 4 || count[0] != 1 {
		t.Errorf("stored count = %v, want a little-endian 1", count)
	}
	entry, err := os.ReadFile(filepath.Join(storeDir, "e0"))
	if err != nil {
		t.Fatalf("ReadFile(e0): %v", err)
	}
	if string(entry) != "1789178907\tGlenn: first\n" {
		t.Errorf("stored entry = %q, want the stamped entry line", entry)
	}
	visits, err := os.ReadFile(filepath.Join(storeDir, "v"))
	if err != nil {
		t.Fatalf("ReadFile(v): %v", err)
	}
	if len(visits) != 4 || visits[0] != 1 {
		t.Errorf("stored visits = %v, want a little-endian 1 for the one render", visits)
	}
}

