// TestExampleGuestbookAppendsAndListsNewestFirst pins the whole submission
// path: a render carrying the collected form fields appends an entry, later
// submissions stack on top, and every later render lists them newest-first
// with the form still present.
func TestExampleGuestbookAppendsAndListsNewestFirst(t *testing.T) {
	render, _ := guestbookExample(t)

	first := render(PageRequest{RequestedAt: stampFirst, RequestData: map[string]string{
		"field_name":    "Glenn",
		"field_message": "hello from the wasm sandbox",
	}})
	wantFirst := ">Guestbook\n\n" + guestbookForm +
		"`T1789178907`T Glenn: hello from the wasm sandbox\n"
	if first != wantFirst {
		t.Fatalf("first submission rendered\n%q\nwant\n%q", first, wantFirst)
	}

	second := render(PageRequest{RequestedAt: stampSecond, RequestData: map[string]string{
		"field_name":    "Ada",
		"field_message": "second entry",
	}})
	wantSecond := ">Guestbook\n\n" + guestbookForm +
		"`T1789178913`T Ada: second entry\n" +
		"`T1789178907`T Glenn: hello from the wasm sandbox\n"
	if second != wantSecond {
		t.Fatalf("second submission rendered\n%q\nwant\n%q", second, wantSecond)
	}

	// A plain visit (no submission) must not add anything.
	third := render(PageRequest{})
	if third != wantSecond {
		t.Errorf("plain visit rendered\n%q\nwant the unchanged page\n%q", third, wantSecond)
	}
}

